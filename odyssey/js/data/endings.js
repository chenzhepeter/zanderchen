// 结局判定：名声高、傲慢低、且救下同伴 → 诗人之名
export function judgeEnding(state) {
  if (state.crew <= 0) return 'LOST';
  if (state.flags.stayedWithCalypso) return 'IMMORTAL';
  const alive = Object.values(state.companions).filter(v => v === 'alive').length;
  if (alive >= 4 && state.kleos >= 60 && state.hubris <= 25) return 'POET';
  if (alive >= 1) return 'TOGETHER';
  return 'ALONE';
}
